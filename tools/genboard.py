"""Generate firmware board headers and the core-module connector table from
the verified pin maps (out_H743.md, out_F429.md)."""
import re
import sys

root = sys.argv[1]
chips = {
    'H743': ('stm32h743iit6', 'STM32H743IIT6 LQFP176', 'STM32H743xx'),
    'F429': ('stm32f429zit6', 'STM32F429ZIT6 LQFP144', 'STM32F429xx'),
}


def parse(path):
    pins, inst = {}, {}
    for l in open(path):
        m = re.match(r'\| (\d+) \| (\S+) \| (\S+) \| (.+) \|$', l)
        if m and m.group(3) not in ('Function', 'RESERVED'):
            pins[m.group(3)] = (int(m.group(1)), m.group(2), m.group(4))
        if l.startswith('Instance choices:'):
            for kv in l.split(':', 1)[1].split(','):
                k, v = kv.strip().split('=')
                inst[k] = v
    return pins, inst


maps = {c: parse(f'{root}/tools/out_{c}.md') for c in chips}
names = set(maps['H743'][0])
assert names == set(maps['F429'][0]), 'logical signal sets differ'

# Core-module connector: every signal that leaves the MCU module, grouped.
groups = ['DISP', 'EXP_SPI', 'I2C_', 'UART_', 'SD_', 'USB_', 'LINUX', 'ESP_', 'IRQ_P', 'ID_P', 'CS_P',
          'INT_B', 'PWR_', 'BOOST', 'IR_', 'BUZZER', 'VIBRATION', 'LED_', 'ADC_H', 'GPIO_H']


def grp(n):
    for i, g in enumerate(groups):
        if n.startswith(g):
            return i
    return len(groups)


order = sorted(names, key=lambda n: (grp(n), n))

for c, (slug, desc, define) in chips.items():
    pins, inst = maps[c]
    out = [f'/* Generated by tools/genboard.py from tools/out_{c}.md. Do not edit by hand. */',
           f'/* {desc}. Alternate-function numbers are NOT included: take them from the datasheet / CubeMX. */',
           f'#ifndef SYN_PINS_{c}_H', f'#define SYN_PINS_{c}_H', '#include "synnefo_pin.h"', '']
    for k, v in sorted(inst.items()):
        out.append(f'#define SYN_{k} {v}')
    out.append('')
    for n in order:
        pos, port, sg = pins[n]
        out.append(f'#define SYN_PIN_{n:<14} SYN_PIN({port[1]}, {port[2:]})  /* pkg pin {pos}, {sg} */')
    out += ['', f'#endif /* SYN_PINS_{c}_H */', '']
    open(f'{root}/firmware/board/pins_{slug}.h', 'w').write('\n'.join(out))

open(f'{root}/firmware/board/synnefo_pin.h', 'w').write('''#ifndef SYNNEFO_PIN_H
#define SYNNEFO_PIN_H
/* A pin is (port letter, number). Use SYN_PIN_PORT / SYN_PIN_NUM to unpack. */
#define SYN_PIN(port, num) (((#port[0] - 'A') << 4) | (num))
#define SYN_PIN_PORT(p) ((p) >> 4)
#define SYN_PIN_NUM(p) ((p) & 0xF)
#endif
''')
open(f'{root}/firmware/board/board_pins.h', 'w').write('''#ifndef BOARD_PINS_H
#define BOARD_PINS_H
#if defined(SYN_MCU_H743)
#include "pins_stm32h743iit6.h"
#elif defined(SYN_MCU_F429)
#include "pins_stm32f429zit6.h"
#else
#error "Define SYN_MCU_H743 or SYN_MCU_F429"
#endif
#endif
''')

# Core-module connector table: fixed pin number per logical signal.
rows = ['| Conn pin | Signal | H743 MCU pin | F429 MCU pin |', '|---|---|---|---|']
for i, n in enumerate(order, 1):
    rows.append(f'| {i} | {n} | {maps["H743"][0][n][1]} | {maps["F429"][0][n][1]} |')
open(f'{root}/tools/connector_table.md', 'w').write('\n'.join(rows) + '\n')
print(len(order), 'signals')
